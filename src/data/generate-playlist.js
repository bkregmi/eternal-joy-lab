const fs = require('fs');
const path = require('path');

const jsonPath = path.join(__dirname, 'tracks.json');
const manualJsonPath = path.join(__dirname, 'manual_tracks.json'); // Define path for manual tracks
const audioRoot = path.join(__dirname, '../../public/media/audio');

const formatName = (fileName) => {
  const base = fileName.replace(/\.[^/.]+$/, ""); // Remove extension
  const parts = base.split('_'); // Split logical segments (Source_Title_Artist)

  const toTitleCase = (str) => {
    return str
      .split('-')
      .filter(word => !!word)
      .map(word => {
        const upper = word.toUpperCase();
        // Keep specific acronyms in uppercase
        if (['JKP', 'EJL', 'JPK', 'ELJ', 'SB'].includes(upper)) return upper;
        // Capitalize first letter of every word
        return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
      })
      .join(' ')
      .trim();
  };

  const formattedParts = parts.map(toTitleCase);

  if (formattedParts.length >= 3) {
    // Result format: Title - Artist (Source)
    return `${formattedParts[1]} - ${formattedParts[2]} (${formattedParts[0]})`;
  } else if (formattedParts.length === 2) {
    // Result format: Source - Title
    return `${formattedParts[0]} - ${formattedParts[1]}`;
  }
  return formattedParts[0];
};

// Folders with unique internal structures to skip auto-generation
const skipFolders = ['SriMadBhagwatGita', 'SriMadBhagawatam'];

const updatePlaylists = () => {
  let finalTrackData = {};

  // 1. Load existing tracks.json (if it exists) as the base.
  // This is crucial to preserve any data not covered by auto-generation or manual_tracks.json.
  if (fs.existsSync(jsonPath)) {
    try {
      finalTrackData = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    } catch (error) {
      console.error(`Error reading existing tracks.json: ${error.message}. Starting with empty data.`);
      finalTrackData = {};
    }
  }

  // 2. Process auto-generated tracks
  if (fs.existsSync(audioRoot)) {
    const folders = fs.readdirSync(audioRoot, { withFileTypes: true })
      .filter(d => d.isDirectory() && !skipFolders.includes(d.name))
      .map(d => d.name);

    folders.forEach(folder => {
      const category = folder.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/[\s_]+/g, '-').toLowerCase();
      const files = fs.readdirSync(path.join(audioRoot, folder)).filter(f => /\.(m4a|mp3)$/i.test(f));
      const autoGeneratedTracks = files.map(f => ({ name: formatName(f), path: `/media/audio/${folder}/${f}` }));
      
      // Overwrite or add auto-generated categories.
      // This ensures that if a folder is rescanned, its content is fresh.
      finalTrackData[category] = autoGeneratedTracks;
      console.log(`✓ Synced auto-generated tracks for ${folder} -> ${category}`);
    });
  }

  // 3. Load and merge manual tracks (manual_tracks.json entries take precedence)
  if (fs.existsSync(manualJsonPath)) {
    try {
      const manualTracks = JSON.parse(fs.readFileSync(manualJsonPath, 'utf8'));
      Object.keys(manualTracks).forEach(category => {
        if (!finalTrackData[category]) {
          // If the category doesn't exist from auto-generation, just add it.
          finalTrackData[category] = manualTracks[category];
        } else if (Array.isArray(finalTrackData[category]) && Array.isArray(manualTracks[category])) {
          // If both are arrays, merge them. Manual entries should override auto-generated ones with the same path.
          const mergedCategoryTracks = [...finalTrackData[category]];
          manualTracks[category].forEach(manualTrack => {
            const existingIndex = mergedCategoryTracks.findIndex(t => t.path === manualTrack.path);
            if (existingIndex !== -1) {
              // Override existing track with manual data
              mergedCategoryTracks[existingIndex] = { ...mergedCategoryTracks[existingIndex], ...manualTrack };
            } else {
              // Add new manual track
              mergedCategoryTracks.push(manualTrack);
            }
          });
          finalTrackData[category] = mergedCategoryTracks;
        } else {
          // If types don't match (e.g., auto-generated is array, manual is object),
          // or if auto-generated is not an array, manual takes full precedence.
          console.warn(`Category '${category}' has conflicting structures. Manual_tracks.json entry will override.`);
          finalTrackData[category] = manualTracks[category];
        }
      });
      console.log('✓ Merged manual tracks from manual_tracks.json.');
    } catch (error) {
      console.error(`Error reading manual_tracks.json: ${error.message}. Continuing without merging manual tracks.`);
    }
  }

  fs.writeFileSync(jsonPath, JSON.stringify(finalTrackData, null, 2) + '\n');
};

updatePlaylists();